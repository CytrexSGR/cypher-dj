#!/usr/bin/env python3
"""Generates the sidechain key rules of package 1.10 slice 5 from docs/schnittstellen/schluessel_regeln.json (plan E20).

Outputs (checked in, never edited by hand):
  djk/kern/include/cypherdj/schluessel_regeln.inc    C++: the cell table [consumer][source][point], the DJ source list and the answer codes
  djk/oberflaeche/projekt/schluessel_tabelle.ts      TypeScript: the same tables for the project server (consumed from unit U3)

Usage: python3 djk/vertrag/erzeuge_schluessel.py            writes the files
       python3 djk/vertrag/erzeuge_schluessel.py --pruefe   exit 1 if a checked-in file differs from what the contract generates
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HIER = Path(__file__).resolve().parent
WURZEL = HIER.parents[1]
VERTRAG = WURZEL / "docs" / "schnittstellen" / "schluessel_regeln.json"
KOPF = "GENERATED by djk/vertrag/erzeuge_schluessel.py from docs/schnittstellen/schluessel_regeln.json. Do not edit by hand."
ANTWORTEN = ["ja", "spaet", "zyklus", "quelle"]   # the code of an answer = its index; the C++ side and the TS side use the same order
VERBRAUCHER = ["spur", "grp", "ret", "pm"]
PUNKTE = ["pre", "post"]
DJ_QUELLEN = {"deck", "erz", "pad"}


def pruefe(d: dict) -> None:
    if d.get("verbraucher") != VERBRAUCHER or d.get("quellen") != VERBRAUCHER or d.get("punkte") != PUNKTE:
        raise ValueError("verbraucher, quellen and punkte must be exactly spur, grp, ret, pm / pre, post (the generated tables index them in this order)")
    if list(d["antworten"]) != ANTWORTEN:
        raise ValueError(f"antworten must be {ANTWORTEN}")
    for v in VERBRAUCHER:
        for q in VERBRAUCHER:
            for p in PUNKTE:
                a = d["zellen"][v][q][p]
                if a not in ANTWORTEN:
                    raise ValueError(f"cell {v}/{q}/{p}: unknown answer {a}")
    for z in d["nur_zeile"]:
        if z["quelle"] not in VERBRAUCHER or z["punkt"] not in PUNKTE:
            raise ValueError(f"nur_zeile {z}: unknown source")
    for art in ("erlaubt", "zyklus", "quelle"):
        for e in d["dj"][art]:
            if e["quelle"] not in DJ_QUELLEN or not 1 <= e["nr"][0] <= e["nr"][1]:
                raise ValueError(f"dj {art}: bad entry {e}")
    gesehen = set()
    for f in d["faelle"]:
        if f["name"] in gesehen:
            raise ValueError(f"case {f['name']}: duplicate")
        gesehen.add(f["name"])
        if f["erwartet"] not in ANTWORTEN + ["nur_zeile"]:
            raise ValueError(f"case {f['name']}: unknown expectation {f['erwartet']}")
        for s in f["stufen"]:
            if s["key"]["q"] not in VERBRAUCHER or s["key"]["punkt"] not in PUNKTE:
                raise ValueError(f"case {f['name']}: bad key")


def erzeuge_cpp(d: dict) -> str:
    z = [f"// {KOPF}", "// Included once by arr_schluessel.h (inside namespace cdj). Index order: spur, grp, ret, pm / pre, post.", ""]
    z.append("constexpr uint8_t SCHL_JA = 0, SCHL_SPAET = 1, SCHL_ZYKLUS = 2, SCHL_QUELLE = 3;   // the answers, in the order of the contract")
    z.append("")
    z.append("// SCHL_ZELLEN[consumer kind][source kind][point]: the answer. Kinds: 0 track, 1 group, 2 return, 3 PM. Point: 0 pre, 1 post.")
    z.append("inline constexpr uint8_t SCHL_ZELLEN[4][4][2] = {")
    for v in VERBRAUCHER:
        zeilen = []
        for q in VERBRAUCHER:
            zeilen.append("{" + ", ".join(f"SCHL_{d['zellen'][v][q][p].upper()}" for p in PUNKTE) + "}")
        z.append("    {" + ", ".join(zeilen) + "},   // consumer " + v)
    z.append("};")
    z.append("")
    z.append("// Sources that exist only as the row sc (the structural form is refused): {source kind, point}.")
    z.append("inline constexpr uint8_t SCHL_NUR_ZEILE[][2] = {")
    for e in d["nur_zeile"]:
        z.append(f"    {{{VERBRAUCHER.index(e['quelle'])}, {PUNKTE.index(e['punkt'])}}},")
    z.append("};")
    z.append("")
    z.append("inline constexpr const char* SCHL_GRUND[] = {\"\", \"sidechain_spaet\", \"sidechain_zyklus\", \"sidechain_quelle\"};   // the reason of an answer, by code")
    z.append("")
    z.append("// DJ sources (decks and sample producer, from unit U2b): {name, first number, last number, answer}. Everything not listed is SCHL_QUELLE.")
    z.append("struct SchlDj {")
    z.append("  const char* quelle;")
    z.append("  int von, bis;")
    z.append("  uint8_t antwort;")
    z.append("};")
    z.append("inline constexpr SchlDj SCHL_DJ[] = {")
    for art, code in (("erlaubt", "SCHL_JA"), ("zyklus", "SCHL_ZYKLUS"), ("quelle", "SCHL_QUELLE")):
        for e in d["dj"][art]:
            z.append(f"    {{\"{e['quelle']}\", {e['nr'][0]}, {e['nr'][1]}, {code}}},")
    z.append("};")
    z.append("")
    return "\n".join(z)


def erzeuge_ts(d: dict) -> str:
    z = [f"// {KOPF}", "", "export type SchluesselAntwort = 'ja' | 'spaet' | 'zyklus' | 'quelle';",
         "export type SchluesselArt = 'spur' | 'grp' | 'ret' | 'pm';",
         "export type SchluesselPunkt = 'pre' | 'post';", ""]
    z.append("/** SCHLUESSEL_ZELLEN[consumer][source][point]: the answer for a stage of the consumer kind keyed by the source kind at the point. */")
    z.append("export const SCHLUESSEL_ZELLEN: Readonly<Record<SchluesselArt, Readonly<Record<SchluesselArt, Readonly<Record<SchluesselPunkt, SchluesselAntwort>>>>>> = {")
    for v in VERBRAUCHER:
        z.append(f"  {v}: {{")
        for q in VERBRAUCHER:
            z.append(f"    {q}: {{ pre: '{d['zellen'][v][q]['pre']}', post: '{d['zellen'][v][q]['post']}' }},")
        z.append("  },")
    z.append("};")
    z.append("")
    z.append("/** Sources that exist only as the row sc: the structural form is refused (the server normalises a track pre key to sc). */")
    z.append("export const SCHLUESSEL_NUR_ZEILE: readonly { readonly quelle: SchluesselArt; readonly punkt: SchluesselPunkt }[] = [")
    for e in d["nur_zeile"]:
        z.append(f"  {{ quelle: '{e['quelle']}', punkt: '{e['punkt']}' }},")
    z.append("];")
    z.append("")
    z.append("/** The reason of an answer other than 'ja'. */")
    z.append("export const SCHLUESSEL_GRUND: Readonly<Record<Exclude<SchluesselAntwort, 'ja'>, string>> = {")
    for a in ANTWORTEN[1:]:
        z.append(f"  {a}: 'sidechain_{a}',")
    z.append("};")
    z.append("")
    z.append("/** DJ sources: every source not listed is 'quelle'. */")
    z.append("export const SCHLUESSEL_DJ: readonly { readonly quelle: string; readonly von: number; readonly bis: number; readonly antwort: SchluesselAntwort }[] = [")
    for art in ("erlaubt", "zyklus", "quelle"):
        antwort = "ja" if art == "erlaubt" else art
        for e in d["dj"][art]:
            z.append(f"  {{ quelle: '{e['quelle']}', von: {e['nr'][0]}, bis: {e['nr'][1]}, antwort: '{antwort}' }},")
    z.append("];")
    z.append("")
    return "\n".join(z)


ZIELE = {
    "djk/kern/include/cypherdj/schluessel_regeln.inc": erzeuge_cpp,
    "djk/oberflaeche/projekt/schluessel_tabelle.ts": erzeuge_ts,
}


def erzeuge(d: dict) -> dict[str, str]:
    pruefe(d)
    return {rel: f(d) for rel, f in ZIELE.items()}


def main(argv: list[str]) -> int:
    d = json.loads(VERTRAG.read_text(encoding="utf-8"))
    ausgabe = erzeuge(d)
    if "--pruefe" in argv:
        fehler = 0
        for rel, soll in ausgabe.items():
            ist = (WURZEL / rel).read_text(encoding="utf-8") if (WURZEL / rel).exists() else None
            if ist != soll:
                print(f"{rel} is not current: python3 djk/vertrag/erzeuge_schluessel.py", file=sys.stderr)
                fehler += 1
        if not fehler:
            print("sidechain key rules: generated files are current")
        return 1 if fehler else 0
    for rel, text in ausgabe.items():
        (WURZEL / rel).write_text(text, encoding="utf-8")
        print("wrote", rel)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
