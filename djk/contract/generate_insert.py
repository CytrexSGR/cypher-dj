#!/usr/bin/env python3
"""Generates the insert vocabulary of package 1.10 slice 4 from docs/interfaces/insert_module.json.

Outputs (checked in, never edited by hand):
  djk/core/signalbox/src/insert_zeilen.inc          C++: the controller-table rows of the kinds with "tabelle": true, plus the
                                                     path list of the whole vocabulary (all kinds, tables or not)
  djk/ui/project/insert_key.ts      TypeScript: kinds, instances, parameters, paths
  djk/conductor/src/insert_controls.ts                TypeScript: the control rows of the kinds with table rows (path, unit, min, max, default) for controls_info.ts
  djk/contract/mock_core/insert_controls.mjs       the same rows for the Attrappe (contract.mjs)

Usage: python3 djk/contract/generate_insert.py            writes the files
       python3 djk/contract/generate_insert.py --pruefe   exit 1 if a checked-in file differs from what the contract generates
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

HIER = Path(__file__).resolve().parent
WURZEL = HIER.parents[1]
VERTRAG = WURZEL / "docs" / "interfaces" / "insert_module.json"
ZIELE = {
    "djk/core/signalbox/src/insert_zeilen.inc": "cpp",
    "djk/ui/project/insert_key.ts": "ts",
    "djk/conductor/src/insert_controls.ts": "ts",
    "djk/contract/mock_core/insert_controls.mjs": "mjs",
}
KOPF = "GENERATED by djk/contract/generate_insert.py from docs/interfaces/insert_module.json. Do not edit by hand."
MAX_PFAD = 31          # ReglerDef::pfad is char[32]
KURVEN = {"schalter", "stufen", "linear"}


def zahl(x: float | int) -> str:
    """Shortest exact spelling, as a C++ float literal and as a JS number."""
    f = float(x)
    s = repr(f)
    if s.endswith(".0"):
        s = s[:-2]
    return s


def cpp_zahl(x: float | int) -> str:
    t = zahl(x)
    return (t + ".0f") if re.fullmatch(r"-?\d+", t) else t + "f"


def ausfalten(daten: dict) -> list[dict]:
    """Every parameter of every instance, in table order (instance by instance), with its full path."""
    ergebnis = []
    for art in daten["arten"]:
        for n in range(1, art["instanzen"] + 1):
            einheiten = [("", None, par) for par in art["parameter"]]
            for g in art.get("gruppen", []):
                for m in range(1, g["anzahl"] + 1):
                    for par in g["parameter"]:
                        p = dict(par)
                        if par["name"] in g.get("vorgabe_je_band", {}):
                            p["vorgabe"] = g["vorgabe_je_band"][par["name"]][m - 1]
                        einheiten.append((f"{g['name']}{m}/", m, p))
            for gruppe, m, par in einheiten:
                ergebnis.append({
                    "art": art["art"], "tabelle": art["tabelle"], "n": n,
                    "pfad": f"{art['praefix']}/{n}/{gruppe}{par['name']}", "par": par,
                })
    return ergebnis


def pruefe(daten: dict) -> None:
    gesehen = set()
    for z in ausfalten(daten):
        p = z["pfad"]
        if len(p) > MAX_PFAD:
            raise ValueError(f"{p}: {len(p)} characters, at most {MAX_PFAD}")
        if p in gesehen:
            raise ValueError(f"{p}: duplicate")
        gesehen.add(p)
        par = z["par"]
        if par["kurve"] not in KURVEN:
            raise ValueError(f"{p}: unknown curve {par['kurve']}")
        if not par["min"] <= par["vorgabe"] <= par["max"]:
            raise ValueError(f"{p}: default {par['vorgabe']} outside {par['min']}..{par['max']}")
        if z["tabelle"] and "rolle" not in par:
            raise ValueError(f"{p}: kind has table rows but the parameter has no role")


def erzeuge_cpp(daten: dict) -> str:
    zeilen = ausfalten(daten)
    z = [f"// {KOPF}", "// Included once by controls.cpp (inside namespace cypherdj::stellwerk). Row order = table order.", ""]
    z.append("struct InsertZeile {")
    z.append("  const char* pfad;")
    z.append("  Rolle rolle;")
    z.append("  float min, max, vorgabe;")
    z.append("  KurvenTyp kurve;")
    z.append("  int rampe_ms;   // switching ramp in ms, 0 for switches and steps")
    z.append("  bool ganz;")
    z.append("};")
    z.append("")
    z.append("inline constexpr InsertZeile INSERT_ZEILEN[] = {")
    for r in zeilen:
        if not r["tabelle"]:
            continue
        p = r["par"]
        z.append(f'    {{"{r["pfad"]}", Rolle::{p["rolle"]}, {cpp_zahl(p["min"])}, {cpp_zahl(p["max"])}, {cpp_zahl(p["vorgabe"])}, '
                 f'KurvenTyp::{p["kurve"]}, {p["rampe_ms"]}, {"true" if p["ganz"] else "false"}}},')
    z.append("};")
    z.append("")
    z.append("// Every path of the vocabulary (all kinds), for the length and uniqueness test. Kinds without table rows are included.")
    z.append("inline constexpr const char* INSERT_VERTRAG_PFADE[] = {")
    for r in zeilen:
        z.append(f'    "{r["pfad"]}",')
    z.append("};")
    z.append("")
    return "\n".join(z)


def erzeuge_regler_liste(daten: dict, mjs: bool) -> str:
    """Rows [path, unit, min, max, default] of the kinds with table rows: for controls_info.ts (units schalter | linear | stufe) and the Attrappe (schalter | lin | stufe)."""
    einheit = {"schalter": "schalter", "linear": "lin" if mjs else "linear", "stufen": "stufe"}
    z = [f"// {KOPF}", "// The control rows ins/<art>/<n>/... of the kinds with \"tabelle\": true, in table order. Compared with insert_zeilen.inc by check_name_lists.py (R03, R05).", ""]
    z.append("export const INSERT_REGLER_ZEILEN" + ("" if mjs else ": readonly (readonly [string, 'schalter' | 'linear' | 'stufe', number, number, number])[]") + " = [")
    for r in ausfalten(daten):
        if not r["tabelle"]:
            continue
        p = r["par"]
        z.append(f"  ['{r['pfad']}', '{einheit[p['kurve']]}', {zahl(p['min'])}, {zahl(p['max'])}, {zahl(p['vorgabe'])}],")
    z.append("];")
    z.append("")
    return "\n".join(z)


def erzeuge_ts(daten: dict) -> str:
    z = [f"// {KOPF}", "", "export type InsertKurve = 'schalter' | 'stufen' | 'linear';",
         "export interface InsertParameter {",
         "  /** Name inside the instance path, e.g. 'schwelle' or 'b1/freq' */ readonly name: string;",
         "  readonly einheit: string; readonly min: number; readonly max: number; readonly vorgabe: number;",
         "  readonly kurve: InsertKurve; readonly ganz: boolean; readonly rampeMs: number;",
         "  /** plugin parameter id in presets/devices.ts, null where the plugin has none */ readonly geraet: string | null;",
         "}", "export interface InsertArt {",
         "  readonly praefix: string; readonly instanzen: number;",
         "  /** latency in samples a stage adds at 48 kHz (delay compensation) */ readonly latenz: number;",
         "  /** the kind has rows in the controller table */ readonly tabelle: boolean;",
         "  readonly parameter: readonly InsertParameter[];", "}", "", "export const INSERT_ARTEN = {"]
    for art in daten["arten"]:
        z.append(f"  {art['art']}: {{ praefix: '{art['praefix']}', instanzen: {art['instanzen']}, latenz: {art.get('latenz', 0)}, "
                 f"tabelle: {'true' if art['tabelle'] else 'false'}, parameter: [")
        # parameters of instance 1 describe every instance (the band defaults differ per band, so they are spelled out)
        erste = [r for r in ausfalten({"arten": [dict(art, instanzen=1)]})]
        for r in erste:
            p = r["par"]
            name = r["pfad"][len(art["praefix"]) + 3:]   # instance 1: "<praefix>/1/"
            g = "null" if p["geraet"] is None else "'" + p["geraet"].replace("<n>", (re.match(r"b(\d+)/", name) or re.match("()", name)).group(1)) + "'"
            z.append(f"    {{ name: '{name}', einheit: '{p['einheit']}', min: {zahl(p['min'])}, max: {zahl(p['max'])}, "
                     f"vorgabe: {zahl(p['vorgabe'])}, kurve: '{p['kurve']}', ganz: {'true' if p['ganz'] else 'false'}, "
                     f"rampeMs: {p['rampe_ms']}, geraet: {g} }},")
        z.append("  ] },")
    z.append("} as const satisfies Record<string, InsertArt>;")
    z.append("")
    z.append("export type InsertArtName = keyof typeof INSERT_ARTEN;")
    z.append("")
    z.append("/** '<praefix>/<n>/<name>' for instance n (1-based) of a kind. */")
    z.append("export function insertPfad(art: InsertArtName, n: number, name: string): string {")
    z.append("  return `${INSERT_ARTEN[art].praefix}/${n}/${name}`;")
    z.append("}")
    z.append("")
    z.append("/** Every path of the vocabulary, in table order (instance by instance). */")
    z.append("export const INSERT_PFADE: readonly string[] = (Object.keys(INSERT_ARTEN) as InsertArtName[]).flatMap((art) =>")
    z.append("  Array.from({ length: INSERT_ARTEN[art].instanzen }, (_, i) => i + 1).flatMap((n) =>")
    z.append("    INSERT_ARTEN[art].parameter.map((p) => insertPfad(art, n, p.name))));")
    z.append("")
    return "\n".join(z)


GERAETE_TS = WURZEL / "djk" / "ui" / "presets" / "devices.ts"


def _ts_parameter(ts: str, geraet: str) -> dict[str, tuple[float, float]]:
    """Plugin parameters of one device in presets/devices.ts: id -> (min, max). Enum parameters read as 0..count-1, switches as 0..1.
    The EQ band parameters come from the function eqBand (ids with `${n}`, returned with the placeholder `<n>`)."""
    a = ts.index("{ id: '%s'" % geraet)
    b = ts.find("\n  { id: '", a + 5)
    text = ts[a:b if b > 0 else len(ts)]
    if geraet == "eq":
        e0 = ts.index("function eqBand")
        text += ts[e0:ts.index("\n}\n", e0)]
    konst = {m.group(1): len(re.findall(r"'[^']*'", m.group(2)))
             for m in re.finditer(r"const (\w+) = \[([^\]]*)\] as const;", ts)}
    erg: dict[str, tuple[float, float]] = {}
    for m in re.finditer(r"zahl\(['`]([\w$\{\}]+)['`], [^,]+, (-?[\d.]+), (-?[\d.]+)", text):
        erg[m.group(1).replace("${n}", "<n>")] = (float(m.group(2)), float(m.group(3)))
    for m in re.finditer(r"schalter\(['`]([\w$\{\}]+)['`]", text):
        erg[m.group(1).replace("${n}", "<n>")] = (0.0, 1.0)
    for m in re.finditer(r"auswahl\(['`]([\w$\{\}]+)['`], [^,]+, (\w+)\)", text):
        erg[m.group(1).replace("${n}", "<n>")] = (0.0, float(konst[m.group(2)] - 1))
    return erg


def pruefe_geraete(daten: dict, ts: str) -> list[str]:
    """Contract against presets/devices.ts: every parameter with a plugin id has the same range there (and the id exists)."""
    fehler = []
    for art in daten["arten"]:
        if not art["geraet"]:
            continue
        plugin = _ts_parameter(ts, art["geraet"])
        vertrag = list(art["parameter"]) + [q for g in art.get("gruppen", []) for q in g["parameter"]]
        for par in vertrag:
            if par["geraet"] is None:
                continue
            gp = plugin.get(par["geraet"])
            if gp is None:
                fehler.append(f"{art['art']}/{par['name']}: id {par['geraet']} is not in presets/devices.ts")
            elif gp != (float(par["min"]), float(par["max"])):
                fehler.append(f"{art['art']}/{par['name']}: contract {par['min']}..{par['max']}, devices.ts {gp[0]}..{gp[1]}")
        ids = {q["geraet"] for q in vertrag if q["geraet"]}
        for pid in plugin:   # and the other way round: every plugin parameter has a contract entry (extsc is the one deliberate gap)
            if pid not in ids and pid != "extsc":
                fehler.append(f"{art['art']}: devices.ts parameter {pid} has no entry in the contract")
    return fehler


def erzeuge(daten: dict) -> dict[str, str]:
    pruefe(daten)
    return {"djk/core/signalbox/src/insert_zeilen.inc": erzeuge_cpp(daten),
            "djk/ui/project/insert_key.ts": erzeuge_ts(daten),
            "djk/conductor/src/insert_controls.ts": erzeuge_regler_liste(daten, False),
            "djk/contract/mock_core/insert_controls.mjs": erzeuge_regler_liste(daten, True)}


def main(argv: list[str]) -> int:
    daten = json.loads(VERTRAG.read_text(encoding="utf-8"))
    ausgabe = erzeuge(daten)
    if "--pruefe" in argv:
        fehler = 0
        for rel, soll in ausgabe.items():
            ist = (WURZEL / rel).read_text(encoding="utf-8") if (WURZEL / rel).exists() else None
            if ist != soll:
                print(f"{rel} is not current: python3 djk/contract/generate_insert.py", file=sys.stderr)
                fehler += 1
        for f in pruefe_geraete(daten, GERAETE_TS.read_text(encoding="utf-8")):
            print(f"contract against presets/devices.ts: {f}", file=sys.stderr)
            fehler += 1
        if not fehler:
            print("insert vocabulary: generated files are current, ranges equal presets/devices.ts")
        return 1 if fehler else 0
    for rel, text in ausgabe.items():
        (WURZEL / rel).write_text(text, encoding="utf-8")
        print("wrote", rel)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
