#!/usr/bin/env python3
"""Generates the container tables from djk/contract/pult.json (single source, frozen interface F1).

Outputs (committed, never edited by hand):
  djk/core/include/cypherdj/pult_table.h   C++ constants (namespace cdj); suffix tables WITHOUT the bk/<k> token
  djk/contract/pult.ts                       TS constants; the regler lists carry the full text incl. bk/<k>
  djk/ui/public/pult.js                      same module as plain JS for the page (no build step)
Usage:
  python3 djk/contract/generate_pult.py            write the three files
  python3 djk/contract/generate_pult.py --liste    print every expanded control path (zug, bus, player, strom), sorted
  python3 djk/contract/generate_pult.py --pruefen  print stale files, exit 1 if any
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

HIER = Path(__file__).resolve().parent
WURZEL = HIER.parents[1]
PULT_JSON = HIER / "pult.json"
ZIELE = {"h": "djk/core/include/cypherdj/pult_table.h", "ts": "djk/contract/pult.ts", "js": "djk/ui/public/pult.js"}
KOPF = ("GENERATED by djk/contract/generate_pult.py from djk/contract/pult.json. Do not edit by hand.\n"
        "Check: python3 djk/contract/generate_pult.py --pruefen")
BK = "bk/<k>"
FAMILIEN = ("zug", "bus", "player", "strom")
SUFFIX = re.compile(r"[a-z0-9_]+(/[a-z0-9_]+)*|bk/<k>")


class PultFehler(Exception):
    pass


def laden(pfad: Path = PULT_JSON) -> dict:
    """Reads and validates pult.json. Anything that is not exactly the frozen shape is a PultFehler."""
    try:
        d = json.loads(Path(pfad).read_text(encoding="utf-8"))
    except (OSError, ValueError) as e:
        raise PultFehler(f"{pfad}: not readable ({e})") from e
    if d.get("format") != "cypherdj-pult/1":
        raise PultFehler("format must be cypherdj-pult/1")
    for k in ("container", "busse", "sends", "master", "cue", "dienste", "bk_n", "strom_n", "player_praefix", "regler",
              "alias", "alias_suffixe", "alias_stroeme", "mix_index"):
        if k not in d:
            raise PultFehler(f"missing key {k}")
    c = d["container"]
    if len(c) != 4:
        raise PultFehler(f"exactly 4 containers expected, found {len(c)}")
    if [x.get("id") for x in c] != ["A", "B", "C", "D"]:
        raise PultFehler("container ids must be A, B, C, D in order")
    if [x.get("player") for x in c] != [1, 2, 3, 4]:
        raise PultFehler("container players must be 1, 2, 3, 4 in order")
    pfade = [x.get("pfad") for x in c]
    if len(set(pfade)) != 4 or not all(isinstance(p, str) and re.fullmatch(r"[a-z]+/[1-9]", p) for p in pfade):
        raise PultFehler(f"container paths must be four unique <kind>/<n> paths, found {pfade}")
    for k in ("busse", "sends"):
        if len(d[k]) != 4 or len(set(d[k])) != 4:
            raise PultFehler(f"{k}: exactly 4 unique paths expected")
    for k in ("bk_n", "strom_n"):
        if not isinstance(d[k], int) or d[k] < 1:
            raise PultFehler(f"{k} must be a positive integer")
    if not re.fullmatch(r"[a-z]+", str(d["player_praefix"])):
        raise PultFehler("player_praefix must be lowercase letters")
    r = d["regler"]
    if set(r) != set(FAMILIEN):
        raise PultFehler(f"regler families must be exactly {FAMILIEN}")
    for fam in FAMILIEN:
        liste = r[fam]
        if not liste:
            raise PultFehler(f"regler.{fam} is empty")
        if len(set(liste)) != len(liste):
            raise PultFehler(f"regler.{fam} has duplicates")
        for s in liste:
            if not isinstance(s, str) or not SUFFIX.fullmatch(s):
                raise PultFehler(f"regler.{fam}: bad suffix {s!r}")
        if BK in liste and (liste[-1] != BK or fam == "player"):
            raise PultFehler(f"regler.{fam}: {BK} must be the last segment and is not allowed in player")
    if r["strom"] != [BK]:
        raise PultFehler("regler.strom must be exactly [bk/<k>]")
    for s in d["alias_suffixe"]:
        if not SUFFIX.fullmatch(s):
            raise PultFehler(f"alias_suffixe: bad suffix {s!r}")
    als = d["alias_stroeme"]
    if (not als or als != sorted(set(als)) or any(not isinstance(n, int) or isinstance(n, bool) or not 1 <= n <= d["strom_n"]
                                                  for n in als)):
        raise PultFehler("alias_stroeme: must be a non-empty ascending list of distinct stream numbers within 1..strom_n")
    erwartet = [x["pfad"] for x in c] + list(d["busse"]) + [d["master"]]
    if d["mix_index"] != erwartet:
        raise PultFehler(f"mix_index must be containers, buses, master in that order: {erwartet}")
    return d


def regler_pfade(d: dict, familie: str) -> list[str]:
    """Every expanded control path of one family, in table order (not sorted)."""
    if familie not in FAMILIEN:
        raise PultFehler(f"unknown family {familie}")
    suff = d["regler"][familie]

    def mit(basis: str) -> list[str]:
        aus = []
        for s in suff:
            if s == BK:
                aus += [f"{basis}/bk/{k}" for k in range(1, d["bk_n"] + 1)]
            else:
                aus.append(f"{basis}/{s}")
        return aus

    if familie == "zug":
        return [p for c in d["container"] for p in mit(c["pfad"])]
    if familie == "bus":
        return [p for b in d["busse"] for p in mit(b)]
    if familie == "player":
        return [p for c in d["container"] for p in mit(f"{d['player_praefix']}/{c['player']}")]
    return [p for n in range(1, d["strom_n"] + 1) for p in mit(f"strom/{n}")]


def _ohne_bk(liste: list[str]) -> list[str]:
    return [s for s in liste if s != BK]


def _q(s: str) -> str:
    return json.dumps(s)


def erzeuge_cpp(d: dict) -> str:
    c, r = d["container"], d["regler"]
    z = ["// " + s for s in KOPF.split("\n")]
    z += ["// The suffix tables hold the suffixes below one strip WITHOUT the bk/<k> token (that family is PULT_BK_N wide).",
          "#pragma once", "", "namespace cdj {", "",
          f"inline constexpr int PULT_CONTAINER = {len(c)};",
          f"inline constexpr int PULT_BUSSE = {len(d['busse'])};",
          f"inline constexpr int PULT_SENDS = {len(d['sends'])};",
          f"inline constexpr int PULT_BK_N = {d['bk_n']};",
          f"inline constexpr int PULT_STROEME = {d['strom_n']};",
          f"inline constexpr const char* PULT_PLAYER_PRAEFIX = {_q(d['player_praefix'])};", "",
          f"inline constexpr const char* PULT_CONTAINER_PFAD[{len(c)}] = {{" + ", ".join(_q(x["pfad"]) for x in c) + "};",
          f"inline constexpr int PULT_CONTAINER_PLAYER[{len(c)}] = {{" + ", ".join(str(x["player"]) for x in c) + "};",
          f"inline constexpr const char* PULT_BUS_PFAD[{len(d['busse'])}] = {{" + ", ".join(_q(x) for x in d["busse"]) + "};",
          f"inline constexpr const char* PULT_SEND_PFAD[{len(d['sends'])}] = {{" + ", ".join(_q(x) for x in d["sends"]) + "};",
          f"inline constexpr int PULT_ALIAS_STROEME_N = {len(d['alias_stroeme'])};",
          f"inline constexpr int PULT_ALIAS_STROEME[PULT_ALIAS_STROEME_N] = {{" + ", ".join(str(n) for n in d["alias_stroeme"]) + "};",
          f"inline constexpr int PULT_MIX_INDEX_N = {len(d['mix_index'])};",
          f"inline constexpr const char* PULT_MIX_INDEX[PULT_MIX_INDEX_N] = {{" + ", ".join(_q(x) for x in d["mix_index"]) + "};", ""]
    for name, fam in (("ZUG", "zug"), ("BUS", "bus"), ("PLAYER", "player")):
        l = _ohne_bk(r[fam])
        z.append(f"inline constexpr int PULT_{name}_N = {len(l)};")
        z.append(f"inline constexpr const char* PULT_{name}_SUFFIX[PULT_{name}_N] = {{")
        z += [f"    {_q(s)}," for s in l]
        z.append("};")
        z.append("")
    z += ["}  // namespace cdj", ""]
    return "\n".join(z)


def _ts_wert(d: dict, typisiert: bool) -> list[str]:
    c = d["container"]
    tupel = lambda l: "[" + ", ".join(_q(x) for x in l) + "]" + (" as const" if typisiert else "")  # noqa: E731
    z = [f"export const pultContainer = {len(c)};", f"export const pultBusse = {len(d['busse'])};",
         f"export const pultSends = {len(d['sends'])};",
         f"export const pultContainerPfad = {tupel([x['pfad'] for x in c])};",
         "export const pultContainerPlayer = [" + ", ".join(str(x["player"]) for x in c) + "]"
         + (" as const;" if typisiert else ";"),
         f"export const pultBusPfad = {tupel(d['busse'])};",
         f"export const pultSendPfad = {tupel(d['sends'])};",
         f"export const pultBkN = {d['bk_n']};", f"export const pultStroeme = {d['strom_n']};",
         f"export const pultPlayerPraefix = {_q(d['player_praefix'])};"]
    for name, fam in (("Zug", "zug"), ("Bus", "bus"), ("Player", "player"), ("Strom", "strom")):
        z.append(f"export const pultRegler{name} = {tupel(d['regler'][fam])};")
    z.append(f"export const pultAliasSuffixe = {tupel(d['alias_suffixe'])};")
    z.append(f"export const PULT_ALIAS_SUFFIXE = {tupel(d['alias_suffixe'])};")
    z.append("export const PULT_ALIAS_STROEME = [" + ", ".join(str(n) for n in d["alias_stroeme"]) + "]"
             + (" as const;" if typisiert else ";"))
    z.append(f"export const pultMixIndexListe = {tupel(d['mix_index'])};")
    sig = "(pfad: string): 1 | 2 | 3 | 4 | null" if typisiert else "(pfad)"
    z += ["", "/** Container number 1..4 for a container path or any control path below it, else null (player N is container N). */",
          f"export function containerVonPfad{sig} {{",
          "  for (let i = 0; i < pultContainerPfad.length; i++) {",
          "    const p = pultContainerPfad[i];",
          "    if (pfad === p || (typeof pfad === 'string' && pfad.startsWith(p + '/') && pfad.length > p.length + 1))"
          + (" return (i + 1) as 1 | 2 | 3 | 4;" if typisiert else " return i + 1;"),
          "  }", "  return null;", "}", "",
          "/** Mixer index (containers 0..3, buses 4..7, master 8) of a strip path or any control path below it, else null. */",
          f"export function pultMixIndex{'(pfad: string): number | null' if typisiert else '(pfad)'} {{",
          "  for (let i = 0; i < pultMixIndexListe.length; i++) {",
          "    const p = pultMixIndexListe[i];",
          "    if (pfad === p || (typeof pfad === 'string' && pfad.startsWith(p + '/') && pfad.length > p.length + 1)) return i;",
          "  }", "  return null;", "}", ""]
    return z


def erzeuge_ts(d: dict) -> str:
    z = ["// " + s for s in KOPF.split("\n")]
    z += ["// The regler lists carry the full suffix text including the bk/<k> token. Erasable syntax only (node type stripping).", ""]
    return "\n".join(z + _ts_wert(d, True))


def erzeuge_js(d: dict) -> str:
    z = ["// " + s for s in KOPF.split("\n")]
    z += ["// Same module as djk/contract/pult.ts, plain JS for the page.", ""]
    return "\n".join(z + _ts_wert(d, False))


def erzeuge(d: dict) -> dict[str, str]:
    return {ZIELE["h"]: erzeuge_cpp(d), ZIELE["ts"]: erzeuge_ts(d), ZIELE["js"]: erzeuge_js(d)}


def pruefen(wurzel: Path = WURZEL) -> list[str]:
    """Stale or missing generated files below `wurzel`, as messages that name the fix."""
    aus = []
    for rel, soll in erzeuge(laden()).items():
        p = Path(wurzel) / rel
        ist = p.read_text(encoding="utf-8") if p.exists() else None
        if ist != soll:
            aus.append(f"{rel} is stale: python3 djk/contract/generate_pult.py")
    return aus


def main(argv: list[str]) -> int:
    try:
        if "--liste" in argv:
            d = laden()
            print("\n".join(sorted({p for f in FAMILIEN for p in regler_pfade(d, f)})))
            return 0
        if "--pruefen" in argv:
            m = pruefen()
            print("\n".join(m) if m else "pult files are current")
            return 1 if m else 0
        for rel, inhalt in erzeuge(laden()).items():
            (WURZEL / rel).write_text(inhalt, encoding="utf-8")
            print(f"written: {rel} ({inhalt.count(chr(10))} lines)")
        return 0
    except PultFehler as e:
        print(f"pult.json: {e}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
