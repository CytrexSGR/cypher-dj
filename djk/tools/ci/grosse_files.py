#!/usr/bin/env python3
"""Size ceiling for source files (called by sieb.sh): a non-generated, non-test file under djk/ (.ts .js .mjs .py .cpp .h .rs) with more than
1000 lines fails the gate, so the big files cannot grow back after a split. Exceptions: djk/tools/grosse_dateien.txt (one path per line, a reason
after ' # '; no line numbers). Generated files carry a "GENERATED by" line in their first 5 lines and need no entry. Tests (tests/ folders,
test_*, *.test.*, *_test.*) and third_party are not checked. An entry whose file is gone or is no longer over the limit is reported as stale
(and fails: delete the line, the ceiling is back for that file).
A listed file must not grow: its line count is compared with the same file at the merge base with origin/main (or HEAD~1 when there is no
merge base); longer fails, unless its reason starts with 'binding table:' (a table that gains one entry per new
row). No listed file may pass 3000 lines.
Exit 0 ok, 1 findings."""
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
GRENZE = 1000
DECKE = 3000   # absolute stop, also for binding tables
TABELLE = "binding table:"   # a reason starting with this lets a listed file grow (one entry per new row), up to DECKE
ENDUNGEN = {".ts", ".js", ".mjs", ".py", ".cpp", ".h", ".rs"}


def ist_test(p: str) -> bool:
    n = p.rsplit("/", 1)[-1]
    return "/tests/" in p or "/third_party/" in p or n.startswith("test_") or ".test." in n or re.search(r"_test\.\w+$", n) is not None


def zeilen(pfad: Path):
    with open(pfad, "rb") as f:
        kopf, n = [], 0
        for z in f:
            n += 1
            if n <= 5:
                kopf.append(z.decode("utf-8", "replace"))
    return n, any("GENERATED by" in z for z in kopf)


def basis():
    for args in (["merge-base", "HEAD", "origin/main"], ["rev-parse", "--verify", "-q", "HEAD~1"]):
        r = subprocess.run(["git", "-C", str(REPO), *args], capture_output=True, text=True)
        if r.returncode == 0 and r.stdout.strip():
            return r.stdout.strip()
    return None


def zeilen_dort(ref, p):
    r = subprocess.run(["git", "-C", str(REPO), "show", f"{ref}:{p}"], capture_output=True)
    return None if r.returncode != 0 else r.stdout.count(b"\n") + (0 if r.stdout.endswith(b"\n") or not r.stdout else 1)


def main() -> int:
    ausnahmen = {}
    liste = REPO / "djk/tools/grosse_dateien.txt"
    for z in liste.read_text().splitlines():
        if z.strip() and not z.startswith("#"):
            pfad, _, grund = z.partition(" # ")
            ausnahmen[pfad.strip()] = grund.strip()
    dateien = subprocess.run(["git", "-C", str(REPO), "ls-files", "djk"], capture_output=True, text=True, check=True).stdout.split("\n")
    zu_gross, gesehen, gewachsen = [], {}, []
    for p in dateien:
        if not p or Path(p).suffix not in ENDUNGEN or ist_test(p) or not (REPO / p).is_file():
            continue
        n, erzeugt = zeilen(REPO / p)
        if n > GRENZE and not erzeugt:
            gesehen[p] = n
            if p not in ausnahmen:
                zu_gross.append((p, n))
    ref = basis()
    for p, n in gesehen.items():
        alt = zeilen_dort(ref, p) if ref and p in ausnahmen else None
        if n > DECKE:
            print(f"::error::{p}: {n} lines, over the absolute stop of {DECKE} lines. Split the file")
            gewachsen.append((p, alt, n))
        elif alt is not None and n > alt and not ausnahmen[p].startswith(TABELLE):
            gewachsen.append((p, alt, n))
    for p, a, n in gewachsen:
        print(f"::error::{p} is listed in djk/tools/grosse_dateien.txt and must not grow: {a} lines at the base, {n} now. Move the new code to another file")
    veraltet = [p for p in ausnahmen if p not in gesehen]
    for p, n in zu_gross:
        print(f"::error::{p}: {n} lines, limit {GRENZE}. Split the file, or (only with a reason) list its path in djk/tools/grosse_dateien.txt")
    for p in veraltet:
        print(f"::error::djk/tools/grosse_dateien.txt lists {p}, but it is gone, generated or under {GRENZE} lines: delete the line")
    for p, g in ausnahmen.items():
        if not g:
            print(f"::error::djk/tools/grosse_dateien.txt: {p} has no reason (path # reason)")
            veraltet.append(p)
    if not (zu_gross or veraltet or gewachsen):
        print(f"size ceiling: no source file over {GRENZE} lines outside {liste.relative_to(REPO)} ({len(gesehen)} listed)")
    return 1 if (zu_gross or veraltet or gewachsen) else 0


sys.exit(main())
