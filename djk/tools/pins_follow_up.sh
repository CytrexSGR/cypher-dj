#!/usr/bin/env bash
# pins_follow_up.sh: one entry point for every pinned count and golden file. Run it before you push.
#
#   djk/tools/pins_follow_up.sh            rewrite every golden that needs no core build, then `git diff --stat` of what changed
#   djk/tools/pins_follow_up.sh --pruefen  compare only: exit 1, naming each drifted pin and the command that fixes it
#
# Why: expected counts and golden files are mirrored by hand in many places; a pin nobody re-pinned turned CI red without a real bug and
# cost a 30 minute round on the capacity-1 runner. CI runs the --pruefen mode right after the export sieve (about 10 s), and
# djk/tools/ci/zeige_error.sh counts failing tests whose text carries "[pin]" as pin drift.
# Every JS golden test honours CYPHERDJ_PINS_SCHREIBEN=1 (ui/tests/support/pins.mjs; the old names ROUTEN_GOLDEN_SCHREIBEN, GOLDEN_SCHREIBEN,
# CYPHERDJ_GOLDEN_SCHREIBEN, CYPHERDJ_FIXTURE_SCHREIBEN and TON_PROBE_SCHREIBEN still work as aliases). Python goldens are regenerated by
# their generator script; no Python test writes a file.
#
# INVENTORY (state of 2026-11-28; "frozen" = recorded from older code on purpose, never regenerate it to make a test green)
# Regenerated here, node tests in djk/ui (compare = plain `node --test tests/<file>`, rewrite = CYPHERDJ_PINS_SCHREIBEN=1 in front):
#   ui/tests/support/routen_golden.json            routes_golden.test.mjs: status, content type and shape of every probed route, plus `tabelle`
#                                                  (router table, read by server_zerlegt.test.mjs). Was: ROUTEN_GOLDEN_SCHREIBEN=1
#   ui/tests/support/gruppen_kopf_golden.json      production_groups_kopf.test.mjs (needs google-chrome). Was: GOLDEN_SCHREIBEN=1
#   ui/tests/golden/ret_seite_ohne_lane.json       production_return_without_lane_golden.test.mjs (needs google-chrome).
#                                                  Was: CYPHERDJ_GOLDEN_SCHREIBEN=1 (the test's deliberate edit of the golden is now idempotent)
#   djk/core/tests/data/wiedergabe_*.json, render_regler_*.json   seam_core_playback.test.mjs: request fixtures the core test
#                                                  test_arr_naht_seite reads. Was: CYPHERDJ_FIXTURE_SCHREIBEN=1
#   djk/instruments/modular_dsp/tests/common/ton-probe.json       sampler_tone_device.test.mjs. Was: TON_PROBE_SCHREIBEN=1
# Regenerated here, other:
#   djk/tests/zaehlstaende.json                    node djk/tools/zaehlstaende.mjs --schreiben (command, tool and route counts)
#   djk/contract/sequences/*.jsonl, INDEX.json     python3 djk/contract/generate_golden.py (compare: check_golden.py)
# Needs a core build (listed in the output, never built here):
#   djk/core/tests/data/arr_start_golden.txt       ninja -C djk/core/build test_arr_start_golden &&
#       djk/core/build/test_arr_start_golden --schreibe djk/core/tests/data/arr_start_golden.txt
#   djk/core/tests/data/wiedergabe_*.json          after a rewrite by naht_kern_wiedergabe: ctest --test-dir djk/core/build -R arr_naht_seite
# Frozen or by hand (no command here, on purpose):
#   ui/tests/support/flach_golden.json (+ flach_golden.mjs), inserts_ohne_golden.json, inserts_mit_golden.json, surge_spur_golden.json:
#       recorded from commits before the feature existed; the tests prove the old behaviour stayed byte-identical.
#   hosts/carla/tests/data/instrumente_surge_golden.json: output of the Surge start script before plan 1.11 task 16; frozen, edit by hand
#       only for the instance letter handling in test_djk_instruments.py.
#   ui/tests/golden/projekte/*/project.json: the 1.x format promise. Only on a format bump: node djk/ui/tests/golden/projekte/generate.mjs,
#       then review the diff of every project.json. golden_projekte.test.mjs and project_flach_golden.test.mjs are not pin drift when red.
#   instruments/rb_dsp/tests/abbildung_golden.rs: a table in the test source, the same table is pinned in the core; edit both by hand.
#   contract/mock_core/berichte/*: reports of measurement runs, not goldens.
set -uo pipefail
REPO=$(cd "$(dirname "$(readlink -f "$0")")/../.." && pwd)
cd "$REPO"
PRUEFEN=0
case "${1:-}" in
  "") ;;
  --pruefen) PRUEFEN=1 ;;
  *) echo "usage: djk/tools/pins_follow_up.sh [--pruefen]" >&2; exit 2 ;;
esac
SELF=djk/tools/pins_follow_up.sh
if [ -n "${CYPHERDJ_PYTHON:-}" ]; then PY=$CYPHERDJ_PYTHON
elif [ -x djk/workshop/.venv/bin/python ]; then PY=djk/workshop/.venv/bin/python
else PY=python3; fi
# the node server tests lock one test instance letter in /dev/shm (ui/tests/support/instance.mjs); another session may hold the default h: take a free one
if [ -z "${CYPHERDJ_TEST_INSTANZ:-}" ]; then
  for L in h f d c b a; do [ -e "/dev/shm/cypherdj-testinstanz-$L.sperre" ] || { export CYPHERDJ_TEST_INSTANZ=$L; break; }; done
fi
CHROME=0; [ -e /usr/bin/google-chrome ] && CHROME=1
# CI sets CYPHERDJ_PINS_OHNE_BROWSER=1: headless Chrome hung for 50 minutes in the runner service (CI 156); the browser goldens are a local check
[ "${CYPHERDJ_PINS_OHNE_BROWSER:-0}" = 1 ] && CHROME=0
FRIST=${CYPHERDJ_PINS_FRIST:-120}   # seconds per test file; a hanging test fails the check instead of holding the runner
DRIFT=()
FEHLER=0

# node_test <file in djk/ui/tests> <pinned file(s) for the message> [needs chrome]
node_test() {
  local datei=$1 pins=$2 chrome=${3:-0}
  if [ "$chrome" = 1 ] && [ "$CHROME" = 0 ]; then echo "skipped (no browser here): $datei -> $pins"; return; fi
  local out rc
  if [ "$PRUEFEN" = 1 ]; then
    out=$(cd djk/ui && env -u CYPHERDJ_PINS_SCHREIBEN timeout -s KILL "$FRIST" node --test "tests/$datei" 2>&1); rc=$?
  else
    out=$(cd djk/ui && CYPHERDJ_PINS_SCHREIBEN=1 timeout -s KILL "$FRIST" node --test "tests/$datei" 2>&1); rc=$?
  fi
  if [ $rc -ne 0 ]; then
    if [ "$PRUEFEN" = 1 ] && printf '%s' "$out" | grep -q '\[pin\]'; then DRIFT+=("$pins|$SELF"); echo "DRIFT  $pins  (djk/ui/tests/$datei)"
    elif [ $rc -eq 137 ]; then FEHLER=1; echo "FAILED djk/ui/tests/$datei: no answer within ${FRIST} s (killed)"
    else FEHLER=1; echo "FAILED djk/ui/tests/$datei (not pin drift: a real failure)"; printf '%s\n' "$out" | grep -A12 'not ok' | head -30; fi
  else echo "ok     $pins"; fi
}

# files generated from docs/interfaces/insert_module.json first: counts and goldens below are derived from them
if [ "$PRUEFEN" = 1 ]; then
  if out=$("$PY" djk/contract/generate_insert.py --pruefe 2>&1); then echo "ok     files generated from insert_module.json"
  else DRIFT+=("files generated from docs/interfaces/insert_module.json|python3 djk/contract/generate_insert.py")
    echo "DRIFT  files generated from insert_module.json"; printf '%s\n' "$out" | tail -8; fi
else
  "$PY" djk/contract/generate_insert.py > /dev/null || { FEHLER=1; echo "FAILED djk/contract/generate_insert.py"; }
fi
node_test routes_golden.test.mjs "djk/ui/tests/support/routen_golden.json"
node_test production_groups_kopf.test.mjs "djk/ui/tests/support/gruppen_kopf_golden.json" 1
node_test production_return_without_lane_golden.test.mjs "djk/ui/tests/golden/ret_seite_ohne_lane.json" 1
node_test seam_core_playback.test.mjs "djk/core/tests/data/wiedergabe_*.json, render_regler_*.json"
node_test sampler_tone_device.test.mjs "djk/instruments/modular_dsp/tests/common/ton-probe.json"
# the router table size must be counted after routen_golden.json was rewritten
if [ "$PRUEFEN" = 1 ]; then
  if out=$(node djk/tools/zaehlstaende.mjs 2>&1); then echo "ok     djk/tests/zaehlstaende.json"
  else DRIFT+=("djk/tests/zaehlstaende.json|$SELF"); echo "DRIFT  djk/tests/zaehlstaende.json"; printf '%s\n' "$out"; fi
  if out=$("$PY" djk/contract/check_golden.py 2>&1); then echo "ok     djk/contract/sequences"
  else DRIFT+=("djk/contract/sequences/*.jsonl|$SELF"); echo "DRIFT  djk/contract/sequences"; printf '%s\n' "$out" | tail -8; fi
else
  node djk/tools/zaehlstaende.mjs --schreiben || FEHLER=1
  "$PY" djk/contract/generate_golden.py > /dev/null || { FEHLER=1; echo "FAILED djk/contract/generate_golden.py"; }
fi

if [ "$PRUEFEN" = 1 ]; then
  if [ ${#DRIFT[@]} -gt 0 ]; then
    echo; echo "pin drift in ${#DRIFT[@]} place(s); fix with one command: $SELF"
    for d in "${DRIFT[@]}"; do echo "  ${d%%|*}"; done
    exit 1
  fi
  [ $FEHLER -eq 0 ] && echo "pins: no drift" ; exit $FEHLER
fi
echo
echo "needs build (not done here):"
echo "  djk/core/tests/data/arr_start_golden.txt: ninja -C djk/core/build test_arr_start_golden &&"
echo "    djk/core/build/test_arr_start_golden --schreibe djk/core/tests/data/arr_start_golden.txt"
echo "  djk/core/tests/data/wiedergabe_*.json (only if listed below as changed): ctest --test-dir djk/core/build -R arr_naht_seite"
echo
git --no-pager diff --stat -- djk/ui/tests/support djk/ui/tests/golden djk/contract/sequences djk/tests/zaehlstaende.json djk/core/tests/data \
  djk/instruments/modular_dsp/tests/common
exit $FEHLER
